afterEvaluate {
    extensions.findByType(com.android.build.gradle.internal.dsl.BaseAppModuleExtension::class.java)?.run {
        applicationVariants.toList().forEach { variant ->
            val variantName = variant.name
            val testTaskName =
                "test${variantName?.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }}UnitTest"

            println("project: ${project.displayName}; variantName: $variantName")
            println("project: ${project.displayName}; testTaskName: $testTaskName")
            variantName?.let { registerReport(variantName = it, testTaskName = testTaskName) }
        }
    }
    extensions.findByType(com.android.build.gradle.LibraryExtension::class.java)?.run {
        libraryVariants.toList().forEach { variant ->
            val variantName = variant.name
            val testTaskName =
                "test${variantName?.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }}UnitTest"

            println("project: ${project.displayName}; variantName: $variantName")
            println("project: ${project.displayName}; testTaskName: $testTaskName")
            variantName?.let { registerReport(variantName = it, testTaskName = testTaskName) }
        }
    }
}

fun registerReport(variantName: String, testTaskName: String) {
    tasks.register<JacocoReport>("jacoco${variantName.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }}Report") {
        group = "Module's Test Coverage"
        description = "Code coverage report for both Android and Unit tests."
        dependsOn(testTaskName)

        reports { reports() }
        setDirectories(variantName, testTaskName)

        finalizedBy("jacoco${variantName.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }}TestCoverage")

//        doLast {
//            serviceOf<ExecOperations>().exec {
//                commandLine("open", "${layout.buildDirectory.get()}/reports/jacoco/jacocoTestReport/html/index.html")
//            }
//        }
    }

    tasks.register<JacocoCoverageVerification>("jacoco${variantName.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }}TestCoverage") {
        group = "Module's Test Coverage"
        description =
            "Generates coverage ratio(./gradlew jacocoAndroidTestCoverage -PminCoverage=0.0)"
        setDirectories(variantName, testTaskName)
        violationRules {
            isFailOnViolation = true
            rule {
                limit {
                    minimum = "0.0".toBigDecimal()
                }
            }
            rule {
                element = "CLASS"
                includes = listOf("org.gradle")
                limit {
                    counter = "LINE"
                    value = "TOTALCOUNT"
                    minimum = "0.0".toBigDecimal()
                }
            }
        }
    }
}
