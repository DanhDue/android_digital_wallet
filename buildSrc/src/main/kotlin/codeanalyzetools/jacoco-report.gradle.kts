fun retrieveSourceDirectoriesTree(variantName: String): ConfigurableFileCollection {
    return files(
        "${project.projectDir}/src/main/java",
        "${project.projectDir}/src/main/kotlin",
        "${project.projectDir}/src/debug/java",
        "${project.projectDir}/src/debug/kotlin",
        "${project.projectDir}/src/${variantName}/java",
        "${project.projectDir}/src/${variantName}/kotlin",
    )
}

fun retrieveClassDirectoriesTree(variantName: String): ConfigurableFileTree {
    return fileTree(layout.buildDirectory) {
        include(
            "**/classes/**/main/**",
            "**/intermediates/classes/${variantName}/**",
            "**/intermediates/javac/${variantName}/classes/**", // Android Gradle Plugin 3.2.x support.
            "**/tmp/kotlin-classes/${variantName}/**",
        )
        exclude(fileFilter)
    }
}

fun retrieveExecutionDataTree(variantName: String, testTaskName: String): ConfigurableFileTree {
    return fileTree(layout.buildDirectory) {
        include(
            "**/jacoco/$testTaskName.exec",
            "**/outputs/unit_test_code_coverage/${testTaskName}/${testTaskName}.exec",
            "**/outputs/code_coverage/**/*.ec",
            "**/jacoco/jacocoTestReport${variantName.replaceFirstChar { if (it.isLowerCase()) it.titlecase(Locale.getDefault()) else it.toString() }}.exec",
            "**/jacoco/${testTaskName}.exec",
            "**/jacoco/test.exec",
        )
    }
}

fun JacocoReportsContainer.reports() {
    xml.required.set(true)
    html.required.set(true)
    xml.outputLocation.set(layout.buildDirectory.file("reports/jacoco/jacocoTestReport/jacocoTestReport.xml"))
    html.outputLocation.set(layout.buildDirectory.dir("reports/jacoco/jacocoTestReport/html"))
}

fun JacocoReport.setDirectories(variantName: String, testTaskName: String) {
    println("JacocoReport.setDirectories(variantName: $variantName)")

    val sourceDirectoriesTree = retrieveSourceDirectoriesTree(variantName)
    println("sourceDirectoriesTree: ${sourceDirectoriesTree.count()}")
    sourceDirectories.setFrom(sourceDirectoriesTree)

    val classDirectoriesTree = retrieveClassDirectoriesTree(variantName)
    println("classDirectoriesTree: ${classDirectoriesTree.count()}")
    classDirectories.setFrom(classDirectoriesTree)

    val executionDataTree = retrieveExecutionDataTree(variantName, testTaskName)
    println("executionDataTree: ${executionDataTree.count()}")
    executionData.setFrom(executionDataTree)
}

fun JacocoCoverageVerification.setDirectories(variantName: String, testTaskName: String) {
